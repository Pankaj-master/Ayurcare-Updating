# ---------- Scoring function ----------
def score_food_row(row, patient_prakriti, needed_doshas, calorie_target_remaining, used_counts):
    """
    row: a pandas Series for one food row (must contain prob_vata/prob_pitta/prob_kapha, calories)
    patient_prakriti: normalized string like "Vata" or "Vata-Pitta"
    needed_doshas: list like ['v','p'] or [] (means maintenance)
    calorie_target_remaining: numeric, used to prefer foods near target per item
    used_counts: dict mapping food->times already used this week (penalty for repeats)
    returns: float score (higher = better)
    """
    # Model probability component: multiply probabilities for required doshas (product) to prefer foods that pacify all requested doshas.
    if needed_doshas:
        p_model = 1.0
        for d in needed_doshas:
            if d.lower() == 'v':
                p_model *= float(row["prob_vata"])
            elif d.lower() == 'p':
                p_model *= float(row["prob_pitta"])
            elif d.lower() == 'k':
                p_model *= float(row["prob_kapha"])
    else:
        # maintenance: average of probs (prefer generally balancing foods)
        p_model = float((row["prob_vata"] + row["prob_pitta"] + row["prob_kapha"]) / 3.0)

    # Prakriti bonus (simple linear combination)
    p = prakriti_weights.get(patient_prakriti, {"vata":0,"pitta":0,"kapha":0})
    prakriti_score = p["vata"]*row["prob_vata"] + p["pitta"]*row["prob_pitta"] + p["kapha"]*row["prob_kapha"]
# Nutrition proximity: we want food calories to be reasonable for a meal item
    # Use a heuristic: prefer items whose calories are near meal target portion
    cal = float(row["calories"]) if not pd.isna(row["calories"]) else 0.0
    # small gaussian-like preference around target/4 (if item size unknown)
    if calorie_target_remaining > 0:
        target_item = max(30.0, calorie_target_remaining / 3.5)  # heuristic
    else:
        target_item = 100.0
    nut_score = np.exp(-abs(cal - target_item) / (target_item + 1.0))
    # repeat penalty
    repeat_pen = used_counts.get(row["food"], 0)

    # combine (weights tunable)
    score = 2.0 * p_model + 1.0 * prakriti_score + 0.8 * nut_score - 1.5 * repeat_pen
    return score

# ---------- Filtering function that uses model predictions (soft) ----------
def filter_by_dosha_model(df, dosha_text, mode="soft", prob_threshold=PROB_THRESHOLD):
    """
    df: foods dataframe with prob_vata/prob_pitta/prob_kapha
    dosha_text: like 'V', 'VP', 'VPK', '' (empty means maintenance)
    mode: "soft" -> keep full df (we'll score by probabilities), "hard" -> filter rows where predicted pacify flag >= threshold
    """
    t = str(dosha_text).upper().replace(" ", "")
    if t == "" or t is None:
        return df.copy()
    mask = pd.Series(True, index=df.index)
    if mode == "hard":
        if "V" in t:
            mask &= (df["pred_pacify_vata"] == 1)
        if "P" in t:
            mask &= (df["pred_pacify_pitta"] == 1)
        if "K" in t:
            mask &= (df["pred_pacify_kapha"] == 1)
        return df[mask].copy()
    else:
        # soft: return full df for scoring (no hard filter)
        return df.copy()

# ---------- Sampling helpers: safe_pick replaced by scorer + greedy pick ----------
def generate_mixed_7_day_diet_model(df, patient_prakriti, needed_doshas, daily_calorie_target=2000):
    """
    df: foods DataFrame with model probs
    patient_prakriti: normalized e.g. "Vata" or "Vata-Pitta"
    needed_doshas: list of 'v','p','k' or empty list for maintenance
    returns: diet dict keyed by day -> {breakfast, lunch, dinner, totals}
    """
    # local copy
    pool_master = df.reset_index(drop=True).copy()
    diet = {}
    used_counts = {}  # track repeats in week

    for day in range(1, 7+1):
        day_meals = {}
        # Define meal calorie split heuristics (can be tuned)
        remaining_daily = daily_calorie_target
        # we choose three meals; approximate item calorie target per meal
        meal_targets = {"breakfast": daily_calorie_target * 0.25, "lunch": daily_calorie_target * 0.45, "dinner": daily_calorie_target * 0.30}

        for meal_name in ["breakfast", "lunch", "dinner"]:
            meal_target = meal_targets[meal_name]
            picks = []
            # We'll pick up to 4 items per meal (same as original)
            local_pool = pool_master.copy()
            for pick_i in range(4):
                # compute scores for each candidate
                local_pool["score"] = local_pool.apply(lambda r: score_food_row(r, patient_prakriti, needed_doshas, meal_target, used_counts), axis=1)
                # sort by score descending
                local_pool_sorted = local_pool.sort_values("score", ascending=False).reset_index(drop=True)
                if local_pool_sorted.empty:
                    break
                # pick top candidate (you may randomize among top-K)
                candidate = local_pool_sorted.iloc[0]
                picks.append(candidate)
                # update used_counts
                used_counts[candidate["food"]] = used_counts.get(candidate["food"], 0) + 1
                # remove that exact food from pool_master for this meal pick to avoid duplicates in same meal
                pool_master = pool_master[pool_master["food"] != candidate["food"]].reset_index(drop=True)
                local_pool = local_pool[local_pool["food"] != candidate["food"]].reset_index(drop=True)
                if local_pool.empty:
                    break

            # convert picks to DataFrame (if empty, create empty df with columns)
            meal_df = pd.DataFrame(picks) if picks else pd.DataFrame(columns=foods.columns)
            day_meals[meal_name] = meal_df

        # compute totals
        totals = {
            "calories": sum(dfm["calories"].sum() if not dfm.empty else 0 for dfm in [day_meals["breakfast"], day_meals["lunch"], day_meals["dinner"]]),
            "protein": sum(dfm["protein"].sum() if not dfm.empty else 0 for dfm in [day_meals["breakfast"], day_meals["lunch"], day_meals["dinner"]]),
            "carbs": sum(dfm["carbs"].sum() if not dfm.empty else 0 for dfm in [day_meals["breakfast"], day_meals["lunch"], day_meals["dinner"]]),
            "fat": sum(dfm["fat"].sum() if not dfm.empty else 0 for dfm in [day_meals["breakfast"], day_meals["lunch"], day_meals["dinner"]])
        }
        day_meals["totals"] = totals
        diet[day] = day_meals

        # After finishing the day, restore pool_master from original df excluding foods with used_counts very high
        # For simplicity, rebuild pool_master from original foods and remove foods used > threshold (e.g., 3 times/week)
        pool_master = df.copy().reset_index(drop=True)
        pool_master = pool_master[~pool_master["food"].isin([f for f,c in used_counts.items() if c > 3])].reset_index(drop=True)

    return diet

