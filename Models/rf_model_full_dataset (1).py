def get_multi_hot_tokens(row, prefix):
    tokens = []
    for col in row.index:
        if col.startswith(prefix + "__") and (row[col] == 1 or str(row[col]) == "1"):
            token = col[len(prefix)+2:].replace("_", " ")
            tokens.append(token)
    return tokens

def ayurvedic_attrs_for_row(row, max_attr_len=80):
    rasa = get_multi_hot_tokens(row, "rasa")
    virya = get_multi_hot_tokens(row, "virya")
    guna = get_multi_hot_tokens(row, "guna")
    vipaka = get_multi_hot_tokens(row, "vipaka")
    rasa_s = ", ".join(rasa) if rasa else "-"
    virya_s = ", ".join(virya) if virya else "-"
    guna_s = ", ".join(guna) if guna else "-"
    vipaka_s = ", ".join(vipaka) if vipaka else "-"
    #dosha_text = row.get("dosha_suitable", "") if "dosha_suitable" in row.index else "-"
    #dosha_text = dosha_text if isinstance(dosha_text, str) and dosha_text.strip() else "-"
    combined = f"Rasa: {rasa_s} | Virya: {virya_s} | Guna: {guna_s} | Vipaka: {vipaka_s}"
    if max_attr_len and len(combined) > max_attr_len:
        return combined[:max_attr_len-3] + "..."
    return combined

