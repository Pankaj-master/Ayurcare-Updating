# ---------- Ingredient extractor & YouTube link generator ----------
def extract_ingredients_from_diet_chart(diet_text: str):
    ingredients = []
    seen = set()
    for line in diet_text.splitlines():
        line = line.strip()
        if "| Cal:" in line or "| Cal:" in line.replace("Cal:", "Cal:"):
            # take left part before '| Cal:'
            left = line.split("| Cal:")[0].strip() if "| Cal:" in line else line.split("| Cal:")[0].strip()
            if "(" in left:
                left = left.split("(")[0].strip()
            ing = left.lower()
            if ing and ing not in seen:
                seen.add(ing)
                ingredients.append(ing)
    return ingredients

def get_recipe_youtube_link(ingredient: str):
    query = quote_plus(f"{ingredient} healthy recipe")
    youtube_search_url = f"https://www.youtube.com/results?search_query={query}"
    recipe_name = f"{ingredient.title()} Recipe"
    return {
        "ingredient": ingredient,
        "recipe_name": recipe_name,
        "youtube_link": youtube_search_url
    }

def get_recipes_from_diet_chart(diet_text: str):
    ingredients = extract_ingredients_from_diet_chart(diet_text)
    recipe_suggestions = []
    for ing in ingredients:
        recipe_suggestions.append(get_recipe_youtube_link(ing))
    return recipe_suggestions

