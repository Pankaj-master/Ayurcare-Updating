def get_feature_names_from_column_transformer(ct, input_features):
    """Return list of feature names after ColumnTransformer transform (scikit-learn >=0.23)."""
    feature_names = []

    # If transformer's remainder='passthrough', the passthrough columns will be appended.
    for name, trans, cols in ct.transformers_:
        if name == "remainder":
            continue
        if hasattr(trans, 'named_steps') and 'ohe' in trans.named_steps:
            # OneHotEncoder inside pipeline
            ohe = trans.named_steps['ohe']
            # get categories in order and build names
            cats = ohe.categories_
            cols_out = []
            for i, orig in enumerate(cols):
                cat_names = [f"{orig}__{str(c)}" for c in cats[i]]
                cols_out.extend(cat_names)
            feature_names.extend(cols_out)
        else:
            # for numeric pipeline, keep original column names
            feature_names.extend(list(cols))

    # handle remainder (passthrough) columns
    if ct.remainder == "passthrough":
        # determine which columns are passthrough
        used_cols = []
        for _, _, cols in ct.transformers_:
            if cols == "remainder":
                continue
            if isinstance(cols, list):
                used_cols.extend(cols)
        # all input features minus used_cols
        passthrough = [c for c in input_features if c not in used_cols]
        feature_names.extend(passthrough)

    return feature_names

